-- Al Capone Nakuru — Supabase (Postgres) schema.
-- Run this once in the Supabase SQL editor: Dashboard → SQL → New query.
-- Safe to run again: every statement is idempotent.
--
-- Row Level Security is enabled on every table with no policies, so the anon and
-- authenticated keys cannot read or write anything directly. The application only
-- talks to Postgres through the server (DATABASE_URL) and to Storage through the
-- service role key.

create table if not exists admins (
  id integer generated by default as identity primary key,
  email text not null unique,
  name text not null,
  password_hash text not null,
  role text not null default 'admin',
  created_at timestamptz not null default now()
);

create table if not exists events (
  id integer generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  tagline text not null default '',
  description text not null default '',
  starts_at timestamptz not null,
  ends_at timestamptz,
  doors_at timestamptz,
  venue text not null default 'Al Capone, Nakuru',
  dress_code text not null default '',
  age_limit text not null default '',
  status text not null default 'draft',
  featured boolean not null default false,
  is_placeholder boolean not null default false,
  cover text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists ticket_types (
  id integer generated by default as identity primary key,
  event_id integer not null references events (id) on delete cascade,
  name text not null,
  description text not null default '',
  price integer not null default 0,
  capacity integer not null default 0,
  sold integer not null default 0,
  sort_order integer not null default 0,
  active boolean not null default true
);

create table if not exists reservations (
  id integer generated by default as identity primary key,
  reference text not null unique,
  name text not null,
  phone text not null,
  email text not null default '',
  date date not null,
  arrival_time text not null default '',
  guests integer not null default 1,
  category text not null default 'General Enquiry',
  seating text not null default '',
  requests text not null default '',
  status text not null default 'new',
  admin_notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists bookings (
  id integer generated by default as identity primary key,
  reference text not null unique,
  event_id integer not null references events (id) on delete restrict,
  name text not null,
  email text not null,
  phone text not null,
  notes text not null default '',
  total integer not null default 0,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists booking_items (
  id integer generated by default as identity primary key,
  booking_id integer not null references bookings (id) on delete cascade,
  ticket_type_id integer not null,
  label text not null,
  unit_price integer not null,
  quantity integer not null
);

create table if not exists tickets (
  id integer generated by default as identity primary key,
  code text not null unique,
  booking_id integer not null references bookings (id) on delete cascade,
  event_id integer not null references events (id) on delete restrict,
  ticket_type_id integer not null references ticket_types (id) on delete restrict,
  holder_name text not null default '',
  status text not null default 'valid',
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists media (
  id integer generated by default as identity primary key,
  filename text not null,
  mime text not null default 'image/jpeg',
  kind text not null default 'image',
  title text not null default '',
  caption text not null default '',
  featured boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists settings (
  key text primary key,
  value text not null default ''
);

-- Unique constraints already index slug, reference and code.
create index if not exists idx_events_status on events (status, starts_at);
create index if not exists idx_reservations_status on reservations (status, created_at);
create index if not exists idx_bookings_status on bookings (status, created_at);
create index if not exists idx_tickets_booking on tickets (booking_id);
create index if not exists idx_tickets_status on tickets (status);
create index if not exists idx_ticket_types_event on ticket_types (event_id);
create index if not exists idx_media_kind on media (kind, created_at);

